  JSR INIT
  JSR SHOW_TITLE_SCREEN

GAME_LOOP:
  JMP GAME_LOOP

INIT:
  LDA #$00
  STA FRAME_COUNTER
  LDA #$FF              ; keep OS ROM, disable BASIC, disable self-test
  STA PORTB
  LDA #$22              ; display list DMA + normal playfield width
  STA SDMCTL
  JSR INIT_COLORS

  LDA #<MY_DISPLAY_LIST
  STA SDLSTL
  LDA #>MY_DISPLAY_LIST
  STA SDLSTL+1

  LDA #<DLI_HANDLER
  STA VDSLST
  LDA #>DLI_HANDLER
  STA VDSLST+1
  LDA #$C0              ; enable DLI and OS VBLANK
  STA NMIEN
  RTS

INIT_COLORS:
  LDA #$00
  STA COLOR4
  STA COLBK
  LDA #$10
  STA COLOR0
  STA COLPF0
  LDA #$20
  STA COLOR1
  STA COLPF1
  LDA #$30
  STA COLOR2
  STA COLPF2
  RTS

DLI_HANDLER:
  PHA
  TXA
  PHA

  LDX #$00
DLI_LOOP:
  STA WSYNC
  LDA START_COLBK,X
  STA COLBK
  LDA START_PF0,X
  STA COLPF0
  LDA START_PF1,X
  STA COLPF1
  LDA START_PF2,X
  STA COLPF2
  INX
  CPX #START_SCREEN_ROWS
  BNE DLI_LOOP

  STA WSYNC
  LDA #$00
  STA COLBK
  STA COLOR4

  PLA
  TAX
  PLA
  RTI

SHOW_TITLE_SCREEN:
WAIT_FOR_START_RELEASE:
  JSR READ_START_KEY
  BEQ WAIT_FOR_START_RELEASE

WAIT_FOR_START_PRESS:
  LDA RTCLOK
WAIT_FRAME:
  CMP RTCLOK
  BEQ WAIT_FRAME
  INC FRAME_COUNTER
  JSR READ_START_KEY
  BNE WAIT_FOR_START_PRESS
  RTS

READ_START_KEY:
  LDA CONSOL
  AND #$01
  RTS

